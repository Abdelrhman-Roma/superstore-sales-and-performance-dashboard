/* ============================================================
   10. CUSTOMER RETENTION / CUSTOMER TYPE ANALYSIS
   ============================================================ */

/*
BUSINESS QUESTION:
How much sales and profit are generated by one-time customers
compared with returning customers?

Customer definition:
- One-Time  = customer with exactly one distinct order
- Returning = customer with more than one distinct order
*/

WITH Customer_Orders AS
(
    SELECT
        Customer_Name,
        sum(sales) as total_sales,
        sum(profit) as total_profit,
        COUNT(DISTINCT Order_ID) AS Number_of_Orders
    FROM Superstore_Cleaned
    GROUP BY Customer_Name
),
customer_type as 
(
    select 
            customer_name,
            total_sales,
            total_profit,
            number_of_orders,
            case 
                when number_of_orders = 1 then 'one-time'
                else 'returning'
            end as customer_type
    from Customer_Orders
)
select 
        customer_type,
        count(*) as number_of_customers,
        sum(total_sales) as total_sales,
        sum(total_profit) as total_profit
from customer_type
group by customer_type;